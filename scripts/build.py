#!/usr/bin/env python3
"""Discover tickets, generate inputs, and compile the book with XeLaTeX."""

from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def generate_inputs(root: Path = ROOT) -> list[Path]:
    files = list((root / "tickets").glob("*.tex"))
    if not files:
        raise ValueError("В tickets/ нет файлов билетов")
    numbered = {}
    for path in files:
        match = re.fullmatch(r"ticket-([0-9]+)\.tex", path.name)
        if not match or int(match[1]) < 1:
            raise ValueError(f"Используйте имя ticket-01.tex: {path.name}")
        number = int(match[1])
        if number in numbered:
            raise ValueError(f"Два файла имеют номер {number}: {numbered[number].name}, {path.name}")
        numbered[number] = path
    ordered = [numbered[number] for number in sorted(numbered)]
    target = root / "generated" / "tickets.tex"
    target.parent.mkdir(exist_ok=True)
    target.write_text(
        "% Generated by scripts/build.py; do not edit.\n"
        + "".join("\\input{" + path.relative_to(root).as_posix() + "}\n" for path in ordered),
        encoding="utf-8",
    )
    return ordered


def main() -> None:
    tickets = generate_inputs()
    if not shutil.which("latexmk") or not shutil.which("xelatex"):
        raise SystemExit("Нужны latexmk и XeLaTeX. Установка описана в CONTRIBUTING.md")
    print(f"Билетов: {len(tickets)}", flush=True)
    subprocess.run(
        ["latexmk", "-xelatex", "-interaction=nonstopmode", "-halt-on-error",
         "-file-line-error", "-outdir=build", "-no-shell-escape", "main.tex"],
        cwd=ROOT, check=True,
    )
    shutil.copyfile(ROOT / "build" / "main.pdf", ROOT / "build" / "tickets.pdf")
    print("Готово: build/tickets.pdf", flush=True)


if __name__ == "__main__":
    main()
